// Run inside the deployed API: docker exec -i griip-internal-messaging-api-1 node --input-type=module < this-file
// Uses the existing adapter/configuration; prints no credentials, signed URLs or user data.
import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import { loadConfig } from "./dist/app/config.js";
import { createBlobStore } from "./dist/infrastructure/storage/index.js";

const config = loadConfig();
assert.equal(config.storage.backend, "s3", "runtime_storage_is_not_s3");
const blobs = createBlobStore(config);
assert.ok(blobs.direct, "runtime_direct_uploads_unavailable");
const id = `col-upload-${randomUUID()}`;
const bytes = Buffer.from(`Meldiq disposable runtime storage probe ${id}`);
const checksum = createHash("sha256").update(bytes).digest("base64");
const request = await blobs.direct.presignPut("profile-photos", id, bytes.length, checksum, 120);
const send = (url, options) => fetch(url, { ...options, signal: AbortSignal.timeout(15000) });
const result = { runtimeAdapter: "s3", syntheticKey: id, userDataTouched: false };
try {
  const preflight = await send(request.url, {
    method: "OPTIONS",
    headers: {
      origin: "https://admin.meldiq.app",
      "access-control-request-method": "PUT",
      "access-control-request-headers": Object.keys(request.headers).filter((name) => name !== "content-length").join(","),
    },
  });
  assert.equal(preflight.status, 200, "approved_origin_preflight_failed");
  assert.equal(preflight.headers.get("access-control-allow-origin"), "https://admin.meldiq.app");
  await preflight.arrayBuffer();
  const tampered = await send(request.url, { method: "PUT", headers: request.headers, body: Buffer.alloc(bytes.length) });
  assert.equal(tampered.status, 400, "checksum_tampering_was_not_rejected");
  await tampered.arrayBuffer();
  const put = await send(request.url, { method: "PUT", headers: request.headers, body: bytes });
  assert.equal(put.status, 200, "signed_put_failed");
  assert.equal(put.headers.get("x-amz-server-side-encryption"), "AES256");
  await put.arrayBuffer();
  const head = await blobs.direct.head("profile-photos", id);
  assert.deepEqual(head, { size: bytes.length, sha256: checksum });
  const stream = await blobs.get("profile-photos", id);
  assert.ok(stream, "runtime_read_failed");
  const chunks = [];
  for await (const chunk of stream) chunks.push(Buffer.from(chunk));
  assert.deepEqual(Buffer.concat(chunks), bytes);
  const overwrite = await send(request.url, { method: "PUT", headers: request.headers, body: bytes });
  assert.equal(overwrite.status, 412, "immutable_object_was_overwritten");
  await overwrite.arrayBuffer();
  const unsignedUrl = new URL(request.url);
  unsignedUrl.search = "";
  const unsigned = await send(unsignedUrl, {});
  assert.equal(unsigned.status, 403, "unsigned_object_was_public");
  await unsigned.arrayBuffer();
  Object.assign(result, { cors: true, checksumBound: true, encrypted: true, exactHeadAndRead: true, overwriteRejected: true, unsignedReadDenied: true });
} finally {
  // This UUID was generated by this invocation; never list or delete unrelated keys.
  await blobs.delete("profile-photos", id);
  assert.equal(await blobs.exists("profile-photos", id), false);
}
console.log(JSON.stringify({ ...result, cleaned: true, ok: true }));
