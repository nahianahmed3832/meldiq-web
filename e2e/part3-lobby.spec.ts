import { expect, test } from "@playwright/test";
import { link } from "./link";
import { newPhone, testAddress } from "./phone";
test.use({ serviceWorkers: "block" });
test.beforeEach(async ({ context }) => context.setExtraHTTPHeaders({ "x-orbit-test-ip": testAddress() }));
test("lobby phone and desktop orders save independently through keyboard controls and can be reset or linked", async ({ page }) => {
  const owner = await newPhone("lobbyorders", "Lobby Owner");
  const org = (await owner.req("POST", "/v1/orgs", { name: "Lobby orders" })).org.id;
  const path = `/v1/orgs/${org}/lobby/settings`;
  const initial = (await owner.req("GET", path)).settings;
  await link(page, owner);
  await expect(page.getByRole("region", { name: "Lobby orders lobby", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Write an intro", exact: true }).click();
  const editor = page.getByRole("complementary", { name: "Customize lobby", exact: true });
  await editor.getByRole("button", { name: "Back to all sections", exact: true }).click();
  await editor.getByRole("button", { name: "Desktop", exact: true }).click();
  const down = editor.getByRole("button", { name: "Move down: About", exact: true });
  await down.focus();
  await page.keyboard.press("Enter");
  await editor.getByRole("button", { name: "Save", exact: true }).click();
  await expect(editor.getByText("No changes yet", { exact: true })).toBeVisible();
  let stored = (await owner.req("GET", path)).settings;
  expect(stored.phoneOrder).toEqual(initial.phoneOrder);
  expect(stored.sections.map((s: any) => s.key)).not.toEqual(initial.sections.map((s: any) => s.key));
  const desktop = stored.sections;
  await editor.getByRole("button", { name: "Phone", exact: true }).click();
  await editor.getByRole("button", { name: "Move up: FAQ", exact: true }).click();
  await editor.getByRole("button", { name: "Save", exact: true }).click();
  await expect(editor.getByText("No changes yet", { exact: true })).toBeVisible();
  stored = (await owner.req("GET", path)).settings;
  expect(stored.sections).toEqual(desktop);
  expect(stored.phoneOrder).not.toEqual(initial.phoneOrder);
  await editor.getByRole("button", { name: "Reset phone order to desktop", exact: true }).click();
  await editor.getByRole("button", { name: "Save", exact: true }).click();
  await expect(editor.getByText("No changes yet", { exact: true })).toBeVisible();
  expect((await owner.req("GET", path)).settings.phoneOrder).toEqual(desktop.map((s: any) => s.key));
  await editor.getByRole("switch", { name: "Link desktop and phone order", exact: true }).click();
  await editor.getByRole("button", { name: "Save", exact: true }).click();
  await expect(editor.getByText("No changes yet", { exact: true })).toBeVisible();
  await page.reload();
  expect((await owner.req("GET", path)).settings.ordersLinked).toBe(true);
});
