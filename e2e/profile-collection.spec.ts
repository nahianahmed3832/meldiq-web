import path from "node:path";
import { expect, test } from "@playwright/test";
import { link } from "./link";
import { newPhone, testAddress } from "./phone";
test.use({ serviceWorkers: "block" });
test.beforeEach(async ({ context }) => context.setExtraHTTPHeaders({ "x-orbit-test-ip": testAddress() }));
test("profile collection previews, claims, equips and resets across devices", async ({ page }, info) => {
  const phone = await newPhone("profilecollect", "Nightwave Explorer");
  await link(page, phone);
  await page.goto("/settings/profile");
  await page.getByRole("button", { name: /Your profile. Your universe/ }).click();
  const studio = page.getByRole("dialog", { name: "Profile collection", exact: true });
  await expect(studio.getByRole("heading", { name: "A little more you." })).toBeVisible();
  await studio.locator(".collection-pick").filter({ hasText: "Ion Halo" }).click();
  await expect(studio.getByRole("button", { name: "Apply look", exact: true })).toBeDisabled();
  expect((await phone.req("GET", "/v2/users/me/profile-customization")).profileStyle.collectibles ?? []).toEqual([]);
  await studio.getByRole("button", { name: "Collect for free", exact: true }).click();
  await expect(studio.getByText("Added to your inventory.", { exact: false })).toBeVisible();
  await studio.getByRole("button", { name: "Apply look", exact: true }).click();
  await expect(studio.getByText("Your look is saved across your devices.")).toBeVisible();
  expect((await phone.req("GET", "/v2/users/me/profile-customization")).profileStyle.collectibles[0].id).toBe("ion-halo");
  await studio.getByRole("button", { name: "Favorite Ion Halo", exact: true }).click();
  await expect(studio.getByRole("button", { name: "Unfavorite Ion Halo", exact: true })).toBeVisible();
  await studio.locator(".collection-pick").filter({ hasText: "Violet Circuit" }).click();
  await expect(studio.getByText("Requires an authorized premium grant.")).toBeVisible();
  await expect(studio.getByRole("button", { name: "Apply look", exact: true })).toBeDisabled();
  await studio.getByRole("button", { name: "Backgrounds", exact: true }).click();
  await studio.locator(".collection-pick").filter({ hasText: "Deep Current" }).click();
  await expect(studio.locator(".collection-profile")).toHaveCSS("background-image", /repeating-linear-gradient/);
  await studio.getByRole("button", { name: "Banners", exact: true }).click();
  await studio.locator(".collection-pick").filter({ hasText: "Blue Horizon" }).click();
  await expect(studio.locator(".collectible-banner")).toBeVisible();
  await page.screenshot({ path: path.join("/tmp", `meldiq-collection-${info.project.name}.png`) });
  expect(await studio.locator(".collection-studio").evaluate((el) => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await studio.getByRole("button", { name: "Reset to default", exact: true }).click();
  await studio.getByRole("button", { name: "Apply look", exact: true }).click();
  await expect(studio.getByText("Your look is saved across your devices.")).toBeVisible();
  expect((await phone.req("GET", "/v2/users/me/profile-customization")).profileStyle.collectibles ?? []).toEqual([]);
});

test("keeps the profile preview visible on a compact phone with a long name", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 740 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  const phone = await newPhone("profilecompact", "N".repeat(80));
  await link(page, phone);
  await page.goto("/settings/profile");
  await page.getByRole("button", { name: /Your profile. Your universe/ }).click();
  const studio = page.getByRole("dialog", { name: "Profile collection", exact: true });
  await expect(studio.locator(".collection-profile")).toBeVisible();
  await studio.locator(".collection-pick").filter({ hasText: "Ion Halo" }).click();
  await expect(studio.locator(".collection-profile .deco-aurora")).toBeVisible();
  expect(await studio.locator(".collection-studio").evaluate((el) => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
});
