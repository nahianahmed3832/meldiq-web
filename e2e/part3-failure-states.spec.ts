import { expect, test } from "@playwright/test";
import { link } from "./link";
import { newPhone, testAddress } from "./phone";
test.use({ serviceWorkers: "block" });
test.beforeEach(async ({ context }) => context.setExtraHTTPHeaders({ "x-orbit-test-ip": testAddress() }));
const outage = (message: string) => ({ status: 503, contentType: "application/json", body: JSON.stringify({ error: { code: "unavailable", message } }) });
test("friends, people lookup, group drafts and Activity distinguish a failed request from an empty result and retry in place", async ({ page }) => {
  const alice = await newPhone("failurealice", "Failure Alice"),
    bob = await newPhone("failurebob", "Failure Bob");
  const org = (await alice.req("POST", "/v1/orgs", { name: "Failure states" })).org.id;
  const code = (await alice.req("POST", `/v1/orgs/${org}/invites`, { role: "MEMBER" })).invite.code;
  await bob.req("POST", "/v1/invites/accept", { code });
  await alice.req("POST", "/v1/connections", { userId: bob.userId });
  await bob.req("POST", "/v1/connections", { userId: alice.userId });
  await link(page, alice);
  await page.route("**/v1/connections", (route) => route.fulfill(outage("Fixture friends outage")), { times: 1 });
  await page.goto("/friends");
  await expect(page.getByRole("alert")).toContainText("Fixture friends outage");
  await expect(page.getByText(/Nobody.s online right now/)).toHaveCount(0);
  await page.getByRole("button", { name: "Try again", exact: true }).click();
  await page.getByRole("tab", { name: "All", exact: true }).click();
  await expect(page.locator(".friend-row")).toContainText("Failure Bob");
  await page.goto("/dms");
  if (page.viewportSize()?.width === 768) await page.getByRole("button", { name: "Show conversations", exact: true }).click();
  await page.getByRole("button", { name: "New message", exact: true }).first().click();
  const lookup = page.getByRole("dialog", { name: "New message", exact: true });
  await page.route("**/v1/users/search?*", (route) => route.fulfill(outage("Fixture people outage")), { times: 1 });
  await lookup.getByRole("textbox", { name: "Find people", exact: true }).fill(bob.username);
  await expect(lookup.getByRole("alert")).toContainText("Fixture people outage");
  await expect(lookup.getByRole("textbox", { name: "Find people", exact: true })).toHaveValue(bob.username);
  await lookup.getByRole("button", { name: "Try again", exact: true }).click();
  await expect(lookup.getByRole("button", { name: /Failure Bob/ })).toBeVisible();
  await lookup.getByRole("textbox", { name: "Find people", exact: true }).fill("nonexistentfixtureperson");
  await expect(lookup).toContainText("No one found.");
  await expect(lookup.getByRole("alert")).toHaveCount(0);
  await lookup.getByRole("textbox", { name: "Find people", exact: true }).fill("");
  await lookup.getByRole("button", { name: /New group/ }).click();
  const group = page.getByRole("dialog", { name: "New group", exact: true });
  await group.getByRole("textbox", { name: "Group name", exact: true }).fill("Retained group draft");
  await page.route("**/v1/users/search?*", (route) => route.fulfill(outage("Fixture group search outage")), { times: 1 });
  await group.getByRole("textbox", { name: "Find people", exact: true }).fill(bob.username);
  await expect(group.getByRole("alert")).toContainText("Fixture group search outage");
  await group.getByRole("button", { name: "Try again", exact: true }).click();
  await group.getByRole("button", { name: /Failure Bob/ }).click();
  await expect(group.getByRole("textbox", { name: "Group name", exact: true })).toHaveValue("Retained group draft");
  const before = (await alice.req("GET", "/v1/conversations")).conversations.length;
  await group.getByRole("button", { name: "Cancel", exact: true }).click();
  expect((await alice.req("GET", "/v1/conversations")).conversations.length).toBe(before);
  await page.route(`**/v1/orgs/${org}/activity`, (route) => route.fulfill(outage("Fixture activity outage")), { times: 1 });
  await page.goto("/activity");
  await expect(page.getByRole("alert")).toContainText("Fixture activity outage");
  await expect(page.getByText("Nothing has changed here recently.", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Try again", exact: true }).click();
  await expect(page.getByRole("alert")).toHaveCount(0);
  await page.keyboard.press(process.platform === "darwin" ? "Meta+k" : "Control+k");
  await page.route("**/v1/search?*", (route) => route.fulfill(outage("Fixture global search outage")), { times: 1 });
  await page.getByRole("combobox", { name: "Search", exact: true }).fill("nonexistentfixtureperson");
  await expect(page.getByRole("alert")).toContainText("Fixture global search outage");
  await expect(page.getByText("Nothing found.", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "Try again", exact: true }).click();
  await expect(page.getByText("Nothing found.", { exact: true })).toBeVisible();
});
